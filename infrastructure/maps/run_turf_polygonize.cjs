const fs = require('fs');
const { polygonize } = require('@turf/polygonize');
const { featureCollection, lineString } = require('@turf/helpers');

const xml = fs.readFileSync('infrastructure/maps/mahmutlar_raw.osm', 'utf8');

// 1. Parse all nodes: id -> [lng, lat]
const nodeRegex = /<node id="(\d+)"[^>]*?lat="([^"]+)"[^>]*?lon="([^"]+)"/g;
const nodes = new Map();
let m;
while ((m = nodeRegex.exec(xml)) !== null) {
  nodes.set(m[1], [parseFloat(m[3]), parseFloat(m[2])]); // [lng, lat]
}
console.log('Nodes parsed:', nodes.size);

// 2. Parse all highway ways
const wayRegex = /<way id="(\d+)"[\s\S]*?<\/way>/g;
const lines = [];

while ((m = wayRegex.exec(xml)) !== null) {
  const wayXml = m[0];
  const wayId = m[1];
  if (!wayXml.includes('k="highway"')) continue;

  const nameMatch = wayXml.match(/<tag k="name" v="([^"]+)"/);
  const name = nameMatch ? nameMatch[1] : '';

  const hwMatch = wayXml.match(/<tag k="highway" v="([^"]+)"/);
  const hwType = hwMatch ? hwMatch[1] : 'road';

  // Include streets, exclude pedestrian footpaths that cut across yards
  if (['footway', 'steps', 'path', 'pedestrian', 'corridor', 'cycleway'].includes(hwType)) continue;

  const ndMatches = [...wayXml.matchAll(/<nd ref="(\d+)"/g)].map(x => x[1]);
  const coords = ndMatches.map(id => nodes.get(id)).filter(Boolean);

  if (coords.length >= 2) {
    lines.push(lineString(coords, { id: wayId, name, hwType }));
  }
}

console.log('Highways converted to LineStrings:', lines.length);

const fc = featureCollection(lines);
const polygons = polygonize(fc);

console.log('Polygons generated by @turf/polygonize:', polygons.features.length);

polygons.features.forEach((feat, idx) => {
  const coords = feat.geometry.coordinates[0];
  // Calculate center
  let sumLng = 0, sumLat = 0;
  coords.forEach(([lng, lat]) => {
    sumLng += lng;
    sumLat += lat;
  });
  const center = [sumLng / coords.length, sumLat / coords.length];
  console.log(`Block ${idx + 1}: ${coords.length} vertices, center: [${center[0].toFixed(5)}, ${center[1].toFixed(5)}]`);
});

fs.writeFileSync('infrastructure/maps/turf_blocks.json', JSON.stringify(polygons, null, 2));
